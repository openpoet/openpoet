package main

import (
	"context"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"time"
)

func main() {
	if len(os.Args) < 2 {
		usage()
		os.Exit(2)
	}
	operation := Operation(os.Args[1])
	if operation != OperationPrepare && operation != OperationPreflight && operation != OperationApply {
		usage()
		os.Exit(2)
	}

	config, err := parseConfig(operation, os.Args[2:])
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(2)
	}
	plan, _ := BuildPlan(operation)
	printPlan(operation, config.Execute, plan)
	if !config.Execute {
		fmt.Println("\ndry-run complete; no action was taken")
		return
	}

	workflow := NewWorkflow(os.Stdout)
	ctx := context.Background()
	switch operation {
	case OperationPrepare:
		manifest, manifestPath, err := workflow.Prepare(ctx, config)
		if err != nil {
			fatal(err)
		}
		fmt.Printf("\nrelease prepared: %s\n", manifest.ReleaseID)
		fmt.Printf("manifest: %s\n", manifestPath)
		fmt.Printf("confirmation token: %s\n", manifest.ConfirmationToken)
		fmt.Println("the token does not authorize a deploy yet; apply also requires explicit human approval")
	case OperationPreflight:
		manifest, err := workflow.Preflight(ctx, config)
		if err != nil {
			fatal(err)
		}
		fmt.Printf("\npreflight OK: %s\n", manifest.ReleaseID)
	case OperationApply:
		result, err := workflow.Apply(ctx, config)
		if err != nil {
			fatal(err)
		}
		fmt.Printf("\napply OK: %s\n", result.ReleaseID)
		fmt.Printf("backup SQLite: %s\n", result.BackupPath)
		fmt.Printf("previous binary: %s\n", result.PreviousBinary)
	}
}

func parseConfig(operation Operation, args []string) (Config, error) {
	cwd, err := os.Getwd()
	if err != nil {
		return Config{}, err
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return Config{}, err
	}

	flags := flag.NewFlagSet(string(operation), flag.ContinueOnError)
	config := Config{
		Operation: operation, EncryptKey: os.Getenv("OPENPOET_ENCRYPT_KEY"), MigrateSecrets: true,
	}
	flags.BoolVar(&config.Execute, "execute", false, "execute the plan; without this flag it is always a dry-run")
	flags.StringVar(&config.ConfirmToken, "confirm-token", "", "exact manifest token; required for a real apply")
	flags.StringVar(&config.RepoDir, "repo", cwd, "OpenPoet repository root")
	flags.StringVar(
		&config.ReleasesDir,
		"releases-dir",
		filepath.Join(home, ".openpoet-rollout", "releases"),
		"immutable releases directory",
	)
	flags.StringVar(&config.ReleaseID, "release-id", "", "safe release ID; generated by prepare when omitted")
	flags.StringVar(&config.ManifestPath, "manifest", "", "manifest.json produced by prepare")
	flags.StringVar(&config.LiveBinary, "live-binary", filepath.Join(cwd, ".run", "openpoet"), "live binary")
	flags.StringVar(&config.DBPath, "db", filepath.Join(cwd, ".run", "openpoet.db"), "production SQLite database")
	flags.StringVar(
		&config.BackupDir,
		"backup-dir",
		filepath.Join(home, ".openpoet-rollout", "backups"),
		"SQLite snapshots directory",
	)
	flags.StringVar(
		&config.PlistPath,
		"plist",
		filepath.Join(cwd, ".run", "openpoet.production.plist"),
		"LaunchAgent plist",
	)
	flags.StringVar(&config.ServiceLabel, "service-label", "local.openpoet.production", "label launchd")
	flags.StringVar(&config.LaunchDomain, "launch-domain", fmt.Sprintf("gui/%d", os.Getuid()), "launchd domain")
	flags.StringVar(&config.HealthURL, "health-url", "http://127.0.0.1:8081/api/version", "health/version endpoint")
	flags.StringVar(&config.RelayURL, "relay-url", "", "DefaultRelayURL embedded in the build")
	flags.DurationVar(&config.StopTimeout, "stop-timeout", 30*time.Second, "graceful stop timeout")
	flags.DurationVar(&config.HealthTimeout, "health-timeout", 45*time.Second, "health gates timeout")
	flags.DurationVar(&config.HealthInterval, "health-interval", 500*time.Millisecond, "health gates interval")
	if err := flags.Parse(args); err != nil {
		return Config{}, err
	}
	if flags.NArg() != 0 {
		return Config{}, fmt.Errorf("unexpected positional arguments: %v", flags.Args())
	}
	if config.HealthInterval <= 0 || config.StopTimeout <= 0 || config.HealthTimeout <= 0 {
		return Config{}, fmt.Errorf("timeouts and intervals must be positive")
	}
	if operation != OperationPrepare && config.ManifestPath == "" && config.Execute {
		return Config{}, fmt.Errorf("--manifest is required with --execute")
	}
	return config, nil
}

func printPlan(operation Operation, execute bool, plan []Step) {
	mode := "DRY-RUN"
	if execute {
		mode = "EXECUTION REQUESTED"
	}
	fmt.Printf("safe-rollout %s [%s]\n", operation, mode)
	for index, step := range plan {
		mutation := ""
		if step.Mutating {
			mutation = " [mutating]"
		}
		fmt.Printf("%d. %s%s — %s\n", index+1, step.Name, mutation, step.Description)
	}
}

func usage() {
	fmt.Fprintln(os.Stderr, "usage: go run ./ops/safe-rollout <prepare|preflight|apply> [flags]")
	fmt.Fprintln(os.Stderr, "default: dry-run. A real apply requires --execute and --confirm-token.")
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "error:", err)
	os.Exit(1)
}
